        public const string TeachInShortCut = "TEACHIN";

        public const string GeneratedHeader ="// AUTO GENERATED by P3.Driver.EepParser from eep.xml - do not edit, change the generator instead";

        private static void AddStringToJObject(string data, string translation, string code, ref JObject jobject)
        {
            var split = data.Split(new[] {"."}, StringSplitOptions.RemoveEmptyEntries);

            var usedJObject = jobject;
            var i = 0;
            foreach (var entry in split)
            {
                if (usedJObject.ContainsKey(entry))
                {
                    usedJObject = usedJObject[entry] as JObject;
                }
                else
                {
                    var newObj = new JObject();
                    usedJObject.Add(entry, newObj);
                    usedJObject = newObj;
                }

                i++;

                if (i == split.Length && !usedJObject.ContainsKey("NAME"))
                {
                    if (!string.IsNullOrEmpty(code))
                        usedJObject.Add("NAME", $"{new JValue(translation)} ({code.Replace("0x", "")})");
                    else
                        usedJObject.Add("NAME", $"{new JValue(translation)}");
                    usedJObject.Add("DESCRIPTION", new JValue(translation));
                }

            }
        }

        public static void GenerateCode(IList<Rorg> rorgs, Dictionary<string, Tuple<long, long>> rangeRefs, GuidLock guidLock, string outDir, ref JObject json)
        {
            var stringBuilder = new StringBuilder();

            foreach (var rorg in rorgs)
            {
                var rorgNumber = rorg.Number.Replace("0x", "");
                stringBuilder.AppendLine("");
                stringBuilder.AppendLine(GeneratedHeader);
                stringBuilder.AppendLine("// -----------------------------------------");
                stringBuilder.AppendLine("// -----------------------------------------");
                stringBuilder.AppendLine($"// {rorg.Number} --------------------------------");
                stringBuilder.AppendLine("// -----------------------------------------");
                stringBuilder.AppendLine("// -----------------------------------------");

                var staticGuids = new List<string>();
                var funcMethods = new StringBuilder();
                var funcStringBuilder = new StringBuilder();

                var rorgGuid = guidLock.Resolve($"Rorg{rorgNumber}Guid", new Guid($"eb2c5295-4a34-4389-8bb5-{rorgNumber}FFFF000000"), 3);
                var rogGuidCode = String.Format(FactoryCodeGeneratorTemplates.RorgStaticGuid, rorgNumber, rorgGuid);

                if(!staticGuids.Contains(rogGuidCode))
                    staticGuids.Add(rogGuidCode);

                foreach (var func in rorg.Functions)
                {
                    var funcNumber = func.Number.Replace("0x", "");
                    var typesMethods = new StringBuilder();
                    var typesStringBuilder = new StringBuilder();

                    var fG = guidLock.Resolve($"Function{rorgNumber}_{funcNumber}Guid",
                        new Guid($"eb2c5295-4a34-4389-8bb5-{rorgNumber}{funcNumber}FF000000"), 3);
                    var funcGuidCode = String.Format(FactoryCodeGeneratorTemplates.FunctionStaticGuid, rorgNumber, funcNumber, fG);
                    func.Guid = fG;
                    if (!staticGuids.Contains(funcGuidCode))
                        staticGuids.Add(funcGuidCode);

                    foreach (var type in func.Types)
                    {
                        var typeNumber = type.Number.Replace("0x", "");
                        var dfMethods = new StringBuilder();
                        var dfStringBuilder = new StringBuilder();

                        var g = new Guid($"eb2c5295-4a34-4389-8bb5-{rorgNumber}{funcNumber}{type.OrigTypeNumber.Replace("0x", "")}000000");
                        g = GenerateNewGuid(g, type.TypeIndex, 3);
                        g = guidLock.Resolve($"Type{rorgNumber}_{funcNumber}_{typeNumber}Guid", g, 3);
                        var typeGuid = String.Format(FactoryCodeGeneratorTemplates.TypeStaticGuid, rorgNumber, funcNumber, typeNumber, g);
                        if (!staticGuids.Contains(typeGuid))
                        {
                            staticGuids.Add(typeGuid);
                        }
                        else
                        {
                            continue;
                        }
                        type.Guid = g;
                        int i = 1;
                        foreach (var dataField in type.DataFields.Values)
                        {
                            var dataFieldName = String.Format(FactoryCodeGeneratorTemplates.AddDataFieldMethodName, rorgNumber, funcNumber,
                                typeNumber, dataField.ShortCut);
                            dfMethods.AppendLine($"{dataFieldName}(factory, interfaceGuid);");
                            var additionalDfProps = new StringBuilder();

                            var dfGuid = guidLock.Resolve($"DataField{rorgNumber}_{funcNumber}_{typeNumber}_{dataField.ShortCut}_Guid",
                                GenerateNewGuid(g, i, 2), 2);

                            var dfGuidCode = String.Format(FactoryCodeGeneratorTemplates.DataFieldStaticGuid,
                                rorgNumber, funcNumber, typeNumber, dataField.ShortCut, dfGuid);

                            if (!staticGuids.Contains(dfGuidCode))
                            {
                                staticGuids.Add(dfGuidCode);
                            }
                            else
                            {
                                continue;
                            }
                            dataField.Guid = dfGuid;

                            additionalDfProps.Append(DataFieldProperties(rorgNumber, funcNumber, typeNumber, dataField, rangeRefs));

                            var dataFieldCode = String.Format(FactoryCodeGeneratorTemplates.AddDataFieldTemplate,
                                rorgNumber, funcNumber, typeNumber, dataField.ShortCut, dataField.Offset, dataField.Length,
                                additionalDfProps, dataField.ShortCut == "LRNB" ? "false" : "true", GetDataFieldValueType(dataField));
                            dfStringBuilder.Append(dataFieldCode);

                            var dataFieldJsonName = String.Format(FactoryCodeGeneratorTemplates.DataFieldName, rorgNumber, funcNumber,
                                typeNumber, dataField.ShortCut);
                            AddStringToJObject(dataFieldJsonName, dataField.Data, null, ref json);

                            i++;
                        }

                        if (type.Outgoing)
                        {
                            dfMethods.Append(FactoryCodeGeneratorTemplates.AddSenderOffsetProperty);

                            var teachInGuid = guidLock.Resolve($"DataField{rorgNumber}_{funcNumber}_{typeNumber}_{TeachInShortCut}_Guid",
                                GenerateNewGuid(g, i, 2), 2);
                            staticGuids.Add(String.Format(FactoryCodeGeneratorTemplates.DataFieldStaticGuid,
                                rorgNumber, funcNumber, typeNumber, TeachInShortCut, teachInGuid));
                            type.TeachInGuid = teachInGuid;
                            var teachInMethod = String.Format(FactoryCodeGeneratorTemplates.AddDataFieldMethodName, rorgNumber, funcNumber,
                                typeNumber, TeachInShortCut);
                            dfMethods.AppendLine($"{teachInMethod}(factory, interfaceGuid);");
                            dfStringBuilder.Append(String.Format(FactoryCodeGeneratorTemplates.AddTeachInTemplate,
                                rorgNumber, funcNumber, typeNumber, TeachInShortCut));
                        }

                        var typeName = String.Format(FactoryCodeGeneratorTemplates.AddTypesMethodName, rorgNumber, funcNumber, typeNumber);
                        typesMethods.AppendLine($"{typeName}(factory, interfaceGuid, enoceanFactory);");

                        var typeJsonName = String.Format(FactoryCodeGeneratorTemplates.TypeName, rorgNumber, funcNumber, typeNumber);
                        AddStringToJObject(typeJsonName, type.Title, type.Number, ref json);

                        var typeCode = String.Format(FactoryCodeGeneratorTemplates.AddTypesTemplate, rorgNumber, funcNumber, typeNumber, dfMethods);
                        typesStringBuilder.Append(typeCode);
                        typesStringBuilder.Append(dfStringBuilder);
                    }

                    foreach (var (status, command) in TwoWayPairs(rorg, func))
                    {
                        var twoWay = new TwoWayType(status, command);
                        var number = twoWay.Number;
                        twoWay.Guid = guidLock.Resolve($"TwoWay{rorgNumber}_{funcNumber}_{number}Guid",
                            new Guid($"eb2c5295-4a34-4389-8bb5-{rorgNumber}{funcNumber}{number}800000"), 3);
                        staticGuids.Add(String.Format(FactoryCodeGeneratorTemplates.TwoWayStaticGuid, rorgNumber, funcNumber, number, twoWay.Guid));

                        var dfMethods = new StringBuilder();
                        var dfStringBuilder = new StringBuilder();
                        var i = 1;
                        foreach (var (caseType, isCommand) in new[] { (status, false), (command, true) })
                        {
                            var caseNumber = caseType.Number.Replace("0x", "");
                            foreach (var dataField in caseType.DataFields.Values.Where(d => d.Guid != Guid.Empty))
                            {
                                // Automatica sets the LRN bit of the answer itself
                                if (isCommand && (dataField.ShortCut == "LRNB" || dataField.ShortCut == "LRN"))
                                {
                                    continue;
                                }

                                var direction = isCommand ? "OUT" : "IN";
                                var fieldType = $"{number}_{direction}";
                                var dfGuid = guidLock.Resolve($"DataField{rorgNumber}_{funcNumber}_{fieldType}_{dataField.ShortCut}_Guid",
                                    GenerateNewGuid(twoWay.Guid, i, 2), 2);
                                staticGuids.Add(String.Format(FactoryCodeGeneratorTemplates.DataFieldStaticGuid,
                                    rorgNumber, funcNumber, fieldType, dataField.ShortCut, dfGuid));
                                twoWay.Fields.Add(new TwoWayField(dataField, caseType, isCommand, dfGuid));

                                dfMethods.AppendLine($"{String.Format(FactoryCodeGeneratorTemplates.AddDataFieldMethodName, rorgNumber, funcNumber, fieldType, dataField.ShortCut)}(factory, interfaceGuid);");
                                dfStringBuilder.Append(String.Format(FactoryCodeGeneratorTemplates.AddTwoWayDataFieldTemplate,
                                    rorgNumber, funcNumber, fieldType, dataField.ShortCut, dataField.Offset, dataField.Length,
                                    DataFieldProperties(rorgNumber, funcNumber, caseNumber, dataField, rangeRefs),
                                    dataField.ShortCut == "LRNB" ? "false" : "true", GetDataFieldValueType(dataField), caseNumber,
                                    isCommand ? "true" : "false"));
                                i++;
                            }
                        }

                        func.TwoWays.Add(twoWay);
                        typesMethods.AppendLine($"{String.Format(FactoryCodeGeneratorTemplates.AddTwoWayMethodName, rorgNumber, funcNumber, number)}(factory, interfaceGuid, enoceanFactory);");
                        AddStringToJObject(String.Format(FactoryCodeGeneratorTemplates.TypeName, rorgNumber, funcNumber, number), status.Title, status.OrigTypeNumber, ref json);
                        typesStringBuilder.Append(String.Format(FactoryCodeGeneratorTemplates.AddTwoWayTemplate, rorgNumber, funcNumber, number, dfMethods));
                        typesStringBuilder.Append(dfStringBuilder);
                    }

                    var funcName =String.Format(FactoryCodeGeneratorTemplates.AddFunctionMethodName, rorgNumber, funcNumber);
                    funcMethods.AppendLine($"{funcName}(factory, interfaceGuid, enoceanFactory);");

                    var funcJsonName = String.Format(FactoryCodeGeneratorTemplates.FunctionName, rorgNumber, funcNumber);
                    AddStringToJObject(funcJsonName, func.Title, func.Number, ref json);

                    var funcCode = String.Format(FactoryCodeGeneratorTemplates.AddFunctionTemplate, rorgNumber, funcNumber, typesMethods);
                    funcStringBuilder.Append(funcCode);
                    funcStringBuilder.Append(typesStringBuilder);
                }
                var rorgCode = String.Format(FactoryCodeGeneratorTemplates.AddRorgTemplate, rorgNumber, funcMethods);

                stringBuilder.Append(String.Join(Environment.NewLine, staticGuids));
                rorg.Guid = rorgGuid;
                stringBuilder.Append(rorgCode);
                stringBuilder.Append(funcStringBuilder);

                var rorgName = String.Format(FactoryCodeGeneratorTemplates.RorgName, rorgNumber);
                AddStringToJObject(rorgName, rorg.Title, rorg.Number, ref json);

                var fileStr = String.Format(FactoryCodeGeneratorTemplates.ClassNameTemplate, rorgNumber, stringBuilder);

                WriteSource(Path.Combine(outDir, $"EnOceanRorg{rorgNumber}Data.cs"), fileStr);

                stringBuilder.Clear();
            }
        }

        /// <summary>
        /// Range, scale, unit and enum properties of a data field; <paramref name="typeNumber"/> names the case the
        /// translation keys belong to.
        /// </summary>
        private static string DataFieldProperties(string rorgNumber, string funcNumber, string typeNumber, DataField dataField,
            Dictionary<string, Tuple<long, long>> rangeRefs)
        {
            var props = new StringBuilder();
            if (dataField.Range != null)
            {
                long min;
                long max;
                if (!String.IsNullOrEmpty(dataField.Range.Ref))
                {
                    if (rangeRefs.ContainsKey(dataField.Range.Ref))
                    {
                        min = rangeRefs[dataField.Range.Ref].Item1;
                        max = rangeRefs[dataField.Range.Ref].Item2;
                    }
                    else
                    {
                        throw new ArgumentException("ref not found");
                    }
                }
                else
                {
                    min = dataField.Range.Min;
                    max = dataField.Range.Max;
                }

                var range = String.Format(FactoryCodeGeneratorTemplates.AddRangeDataField,
                    rorgNumber, funcNumber, typeNumber, dataField.ShortCut, min.ToString(CultureInfo.InvariantCulture), max.ToString(CultureInfo.InvariantCulture));
                props.Append(range);
            }
            if (dataField.Scale != null)
            {
                var scale = String.Format(FactoryCodeGeneratorTemplates.AddScaleDataField,
                    rorgNumber, funcNumber, typeNumber, dataField.ShortCut, dataField.Scale.Min.ToString(CultureInfo.InvariantCulture), dataField.Scale.Max.ToString(CultureInfo.InvariantCulture));
                props.Append(scale);
            }

            if (!String.IsNullOrEmpty(dataField.Unit))
            {
                var unit = String.Format(FactoryCodeGeneratorTemplates.AddUnitDataField,
                    rorgNumber, funcNumber, typeNumber, dataField.ShortCut, dataField.Unit.Replace("\"", "\"\""));
                props.Append(unit);
            }

            if (dataField.BoolEnum)
            {
                var enumeration = String.Format(FactoryCodeGeneratorTemplates.AddEnumMinMaxField,
                    rorgNumber, funcNumber, typeNumber, dataField.ShortCut,
                    dataField.Enumeration.First.Min!.Value.ToString(CultureInfo.InvariantCulture),
                    dataField.Enumeration.First.Max!.Value.ToString(CultureInfo.InvariantCulture),
                    dataField.Enumeration.Second.Min!.Value.ToString(CultureInfo.InvariantCulture),
                    dataField.Enumeration.Second.Max!.Value.ToString(CultureInfo.InvariantCulture));
                props.Append(enumeration);
            }

            return props.ToString();
        }

        /// <summary>
        /// Writes UTF-8 with BOM and CRLF like the rest of the repository.
        /// </summary>
        public static void WriteSource(string path, string content)
        {
            var normalized = content.Replace("\r\n", "\n").Replace("\n", "\r\n");
            File.WriteAllText(path, normalized, new UTF8Encoding(true));
        }

        /// <summary>
        /// A5-20-01..06 HVAC components: the device sends the status case and only listens right after it for the command
        /// case. Both cases of the type become one device template.
        /// </summary>
        private static IEnumerable<(Model.Type Status, Model.Type Command)> TwoWayPairs(Rorg rorg, Function func)
        {
            if (rorg.Number != "0xA5" || func.Number != "0x20")
            {
                yield break;
            }

            foreach (var cases in func.Types.Where(t => t.Guid != Guid.Empty).GroupBy(t => t.OrigTypeNumber))
            {
                var typeNumber = Convert.ToInt32(cases.Key.Replace("0x", ""), 16);
                var list = cases.ToList();
                if (typeNumber >= 0x01 && typeNumber <= 0x06 && list.Count == 2)
                {
                    yield return (list[0], list[1]);
                }
            }
        }

        private static string GetDataFieldValueType(DataField dataField)
        {
            if (dataField.Scale != null || dataField.Segments.Count > 0)
            {
                return "NodeDataType.Double";
            }
            if (dataField.ShortCut == "WIN")
            {
                // F6-10-00 / D2-03-10 window handle, decoded by EnOceanWinData
                return "NodeDataType.WindowState";
            }
            if (dataField.Length == 1 || dataField.BoolEnum)
            {
                return "NodeDataType.Boolean";
            }
            return "NodeDataType.Integer";
        }

        private static Guid GenerateNewGuid(Guid guid, int c, int index)
        {
            byte[] gu = guid.ToByteArray();

            gu[gu.Length - index] = (byte)(Convert.ToInt32(gu[gu.Length - index]) + c);

            return new Guid(gu);
        }
